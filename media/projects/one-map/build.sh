#!/usr/bin/env bash
# Build "One Map" end to end: narration + word times, assemble the film in the pinned Lemo-Opuscar transit-map
# engine, events, score + mix, picture (WebGL, ~17 s render per film second on CPU), master, QA.
# usage: media/projects/one-map/build.sh     -> media/out/one-map.mp4 (+ .check.jpg)
set -euo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)/env.sh"
P="$MEDIA_ROOT/projects/one-map"; B="$MEDIA_ROOT/.build/one-map"; OUT="$MEDIA_ROOT/out"; PIPE="$MEDIA_ROOT/pipeline"
ENGINE="$LEMO_DIR/styles/transit-map/demo"; FILM="$LEMO_DIR/styles/transit-map/yourider-one-map"
DUR=$("$MEDIA_PY" -c "import json,sys;print(json.load(open(sys.argv[1]))['duration'])" "$P/script.json")
mkdir -p "$B" "$OUT" "$FILM/fonts"

"$MEDIA_PY" "$PIPE/voice.py" "$P" "$B"

# film folder: the generic engine (gl.js, film.js) from the pinned library + our network, direction and score
cp "$ENGINE/gl.js" "$ENGINE/film.js" "$FILM/"
cp "$P/net.js" "$P/timeline.js" "$P/audio.py" "$FILM/"
cp "$MEDIA_TOOLS/web/Inter.woff2" "$FILM/fonts/"
# English-only film: the engine waits on a CJK font we do not ship
grep -q "^const fontList = \[" "$FILM/film.js" || { echo "engine changed: fontList not found in film.js" >&2; exit 1; }
sed -i "s/^const fontList = \[.*\];/const fontList = ['400 20px Inter', '500 20px Inter', '600 20px Inter', '700 20px Inter', '800 20px Inter'];/" "$FILM/film.js"
cat > "$FILM/index.html" <<'HTML'
<!doctype html>
<html><head><meta charset="utf-8">
<style>
@font-face{font-family:Inter;src:url(fonts/Inter.woff2) format('woff2');font-weight:100 900}
html,body{margin:0;background:#0f0f10;overflow:hidden}
canvas{display:block;position:absolute;left:0;top:0}
</style>
</head><body>
<canvas id="gl"></canvas><canvas id="ov"></canvas>
<script src="net.js"></script>
<script src="gl.js"></script>
<script type="module" src="film.js"></script>
</body></html>
HTML
"$MEDIA_PY" -c "import json,sys;d=json.load(open(sys.argv[1]));open(sys.argv[2],'w').write('// generated by build.sh from words.json (Whisper word times, film seconds)\nexport const WORDS = '+json.dumps(d)+';\n')" "$B/words.json" "$FILM/words.js"

cd "$LEMO_DIR"
REL="styles/transit-map/yourider-one-map"
node core/render/events.mjs "$REL"
"$MEDIA_PY" "$FILM/audio.py" "$B"
node core/render/video.mjs "$REL" --fps 30 --workers "${WORKERS:-4}" --out "$B/video.mp4"
"$PIPE/master.sh" "$B/video.mp4" "$FILM/mix.wav" "$OUT/one-map.mp4" "$DUR"

# the beat of silence between the last word of L5 and Closed Won landing must really be silent
SIL=$("$MEDIA_PY" -c "import json,sys;e=json.load(open(sys.argv[1]));c={x['type']:x['t'] for x in e['ev']};print(f\"{c['silence']+.12:.2f}:{c['arrive']-.1:.2f}\")" "$FILM/events.json")
"$MEDIA_PY" "$PIPE/check.py" "$OUT/one-map.mp4" --words "$B/words.json" --sheet "$OUT/one-map.check.jpg" --silence "$SIL"
