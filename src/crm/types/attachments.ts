/**
 * Direct insert into `attachments`.
 *
 * Prefer `app.attach_file()`: it resolves the organization from the file,
 * records agent attribution, and writes the `file_attached` timeline entry. A
 * caller assembling this by hand has to remember all three.
 */
export interface AttachmentInsert {
  organization_id: OrganizationId;
  file_id: FileId;
  entity_type: CrmEntity;
  entity_id: string;
  role?: AttachmentRole;
  label?: string | null;
  sort_order?: number;
  attached_by?: UserId | null;
}

/** Arguments to `app.attach_file()`. */
export interface AttachFileArgs {
  file_id: FileId;
  entity_type: CrmEntity;
  entity_id: string;
  role?: AttachmentRole;
  label?: string | null;
}

